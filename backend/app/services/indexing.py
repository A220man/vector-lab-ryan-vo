def compute_hash(text: str) -> str:
    """Compute SHA-256 hash of text content."""
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def build_tree_from_pages(pages: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    """
    Build hierarchical tree structure from flat page list.
    This is a simplified version - real implementation would use LLM for structure detection.
    """
    nodes = []
    for i, page in enumerate(pages):
        # Simple heuristic: lines starting with "Chapter" or "Section" are headers
        lines = page["text"].split("\n")
        structure_num = f"{i + 1}"
        title = lines[0] if lines else f"Page {page['page_num']}"
        content = page["text"]

        node = {
            "node_id": compute_hash(f"{page['page_num']}:{title}")[:16],
            "structure": structure_num,
            "title": title,
            "content": content,
            "content_hash": compute_hash(content),
            "level": 0 if "Chapter" in title else 1,
            "parent_node_id": None,
            "start_page": page["page_num"],
            "end_page": page["page_num"],
        }
        nodes.append(node)

    # Build parent-child relationships based on level
    for i, node in enumerate(nodes):
        if node["level"] > 0:
            # Find nearest previous node with lower level
            for j in range(i - 1, -1, -1):
                if nodes[j]["level"] < node["level"]:
                    node["parent_node_id"] = nodes[j]["node_id"]
                    break

    return nodes


async def build_index(document: Document, pages: List[Dict[str, Any]], session: AsyncSession) -> List[IndexNode]:
    """Build full index tree for a document."""
    tree_nodes = build_tree_from_pages(pages)

    db_nodes = []
    for node_data in tree_nodes:
        node = IndexNode(
            document_id=document.id,
            node_id=node_data["node_id"],
            structure=node_data["structure"],
            title=node_data["title"],
            content=node_data["content"],
            content_hash=node_data["content_hash"],
            summary=None,  # Would be generated by LLM
            summary_hash=None,
            level=node_data["level"],
            parent_node_id=node_data["parent_node_id"],
            start_page=node_data["start_page"],
            end_page=node_data["end_page"],
        )
        session.add(node)
        db_nodes.append(node)

    document.page_count = len(pages)
    await session.commit()

    for node in db_nodes:
        await session.refresh(node)

    return db_nodes


async def incremental_update_index(
    document: Document,
    new_pages: List[Dict[str, Any]],
    session: AsyncSession,
) -> List[str]:
    """
    Perform incremental index update.
    Compares new content hashes with existing nodes, only rebuilds changed subtrees.
    Returns list of changed node_ids.
    """
    # Get existing nodes
    result = await session.execute(
        select(IndexNode).where(IndexNode.document_id == document.id)
    )
    existing_nodes = {n.node_id: n for n in result.scalars().all()}

    # Build new tree
    new_tree_nodes = build_tree_from_pages(new_pages)
    new_node_map = {n["node_id"]: n for n in new_tree_nodes}

    changed_node_ids = []

    # Find changed nodes (content hash differs or new node)
    for node_id, new_node in new_node_map.items():
        existing = existing_nodes.get(node_id)
        if not existing:
            # New node
            changed_node_ids.append(node_id)
        elif existing.content_hash != new_node["content_hash"]:
            # Content changed
            changed_node_ids.append(node_id)
            # Update existing node
            existing.content = new_node["content"]
            existing.content_hash = new_node["content_hash"]
            existing.title = new_node["title"]
            existing.structure = new_node["structure"]
            existing.level = new_node["level"]
            existing.parent_node_id = new_node["parent_node_id"]
            existing.start_page = new_node["start_page"]
            existing.end_page = new_node["end_page"]
            # Invalidate summary - will be regenerated
            existing.summary = None
            existing.summary_hash = None

    # Find deleted nodes
    for node_id, existing in existing_nodes.items():
        if node_id not in new_node_map:
            # Node deleted - mark for removal
            await session.delete(existing)
            changed_node_ids.append(node_id)

    # Propagate changes up to parents (invalidate summaries)
    for node_id in changed_node_ids:
        await _invalidate_parent_summaries(node_id, new_node_map, existing_nodes, session)

    document.page_count = len(new_pages)
    await session.commit()

    return changed_node_ids


async def _invalidate_parent_summaries(
    node_id: str,
    new_node_map: Dict[str, Dict],
    existing_nodes: Dict[str, IndexNode],
    session: AsyncSession,
):
    """Walk up the tree invalidating summaries of ancestors."""
    # Find parent in new map
    new_node = new_node_map.get(node_id)
    parent_id = new_node.get("parent_node_id") if new_node else None

    while parent_id:
        parent = existing_nodes.get(parent_id)
        if parent:
            parent.summary = None
            parent.summary_hash = None
        # Continue up
        parent_new = new_node_map.get(parent_id)
        parent_id = parent_new.get("parent_node_id") if parent_new else None


async def get_tree_structure(doc_id: int, session: AsyncSession) -> Dict[str, Any]:
    """Get full tree structure for a document."""
    result = await session.execute(
        select(IndexNode).where(IndexNode.document_id == doc_id).order_by(IndexNode.level, IndexNode.structure)
    )
    nodes = result.scalars().all()

    # Build tree
    node_map = {n.node_id: n for n in nodes}
    root_nodes = []

    for node in nodes:
        node_dict = {
            "node_id": node.node_id,
            "structure": node.structure,
            "title": node.title,
            "content": node.content,
            "summary": node.summary,
            "level": node.level,
            "parent_node_id": node.parent_node_id,
            "start_page": node.start_page,
            "end_page": node.end_page,
            "content_hash": node.content_hash,
            "summary_hash": node.summary_hash,
            "nodes": [],  # children
        }
        node_map[node.node_id] = node_dict

    # Second pass to build hierarchy
    for node in nodes:
        if node.parent_node_id and node.parent_node_id in node_map:
            parent = node_map[node.parent_node_id]
            parent["nodes"].append(node_map[node.node_id])
        else:
            root_nodes.append(node_map[node.node_id])

    return {"nodes": root_nodes} if root_nodes else {}


async def get_leaf_nodes(doc_id: int, session: AsyncSession) -> List[Dict[str, Any]]:
    """Get all leaf nodes (nodes without children)."""
    result = await session.execute(
        select(IndexNode).where(IndexNode.document_id == doc_id)
    )
    nodes = result.scalars().all()

    # Build children map
    children_map = {}
    for node in nodes:
        if node.parent_node_id:
            children_map.setdefault(node.parent_node_id, []).append(node.node_id)

    leaves = []
    for node in nodes:
        if node.node_id not in children_map:
            leaves.append({
                "node_id": node.node_id,
                "structure": node.structure,
                "title": node.title,
                "content": node.content,
                "summary": node.summary,
                "level": node.level,
                "start_page": node.start_page,
                "end_page": node.end_page,
            })

    return leaves


async def search_nodes(
    doc_id: int,
    query: str,
    limit: int,
    session: AsyncSession,
) -> List[Dict[str, Any]]:
    """Simple text search in node content and titles."""
    result = await session.execute(
        select(IndexNode)
        .where(IndexNode.document_id == doc_id)
    )
    nodes = result.scalars().all()

    query_lower = query.lower()
    matches = []
    for node in nodes:
        title_match = query_lower in (node.title or "").lower()
        content_match = query_lower in (node.content or "").lower()
        summary_match = query_lower in (node.summary or "").lower()

        if title_match or content_match or summary_match:
            matches.append({
                "node_id": node.node_id,
                "structure": node.structure,
                "title": node.title,
                "summary": node.summary,
                "level": node.level,
                "match_type": "title" if title_match else ("content" if content_match else "summary"),
            })
            if len(matches) >= limit:
                break

    return matches